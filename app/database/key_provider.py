"""Injected authority contract. No credentials, default provider or key custody."""
from dataclasses import dataclass
from typing import Protocol


class KeyUnavailable(RuntimeError):
    """Redacted authority/authentication failure; never include payloads or keys."""


@dataclass(frozen=True)
class PayloadContext:
    namespace: str
    payload_id: str
    purpose: str
    owner_digest: str

    def as_dict(self):
        return dict(namespace=self.namespace, payload_id=self.payload_id,
                    purpose=self.purpose, owner_digest=self.owner_digest)


@dataclass(frozen=True)
class KeyGrant:
    reference: str
    key: bytes
    generation: int


class KeyProvider(Protocol):
    def schema_required(self, namespace: str) -> bool: ...
    def database_state(self, namespace: str) -> dict: ...
    def resolve_migration(self, namespace: str, original: str, current: str, authorization: str, *, committed: bool = True) -> None: ...
    def check_database(self, namespace: str, fingerprint: str) -> None: ...
    def begin_database(self, namespace: str, fingerprint: str) -> None: ...
    def finish_database(self, namespace: str, fingerprint: str, schema: bool) -> None: ...
    def allocate(self, context: PayloadContext, operation: str) -> KeyGrant: ...
    def expected(self, reference: str) -> PayloadContext: ...
    def unwrap(self, reference: str, context: PayloadContext) -> KeyGrant: ...
    def prepare_erasure(self, action: str, context: PayloadContext, reference: str) -> None: ...
    def erasure(self, action: str) -> dict: ...
    def revoke(self, action: str) -> bool: ...
    def rewrap(self, reference: str, operation: str) -> int: ...
    def retire_generation(self, generation: int, *, recovery_acknowledged: bool) -> None: ...
